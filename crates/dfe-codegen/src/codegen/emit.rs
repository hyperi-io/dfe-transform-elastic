//! Pipeline-level code generation.
//!
//! Emits a complete `.rs` file with a struct implementing `Transform` for
//! a parsed Elastic ingest pipeline.

use anyhow::{Context, Result};

use crate::pipeline::Pipeline;

use super::processor::emit_processor;

/// Generate Rust source code from a parsed pipeline.
pub struct PipelineCodegen<'a> {
    pipeline: &'a Pipeline,
    /// Module name used for the struct name (e.g., "cisco_asa" → "CiscoAsa").
    module_name: String,
}

impl<'a> PipelineCodegen<'a> {
    pub fn new(pipeline: &'a Pipeline, module_name: &str) -> Self {
        Self {
            pipeline,
            module_name: module_name.to_string(),
        }
    }

    /// Generate the complete Rust source file.
    pub fn generate(&self) -> Result<String> {
        let struct_name = to_pascal_case(&self.module_name);
        let mut out = String::with_capacity(4096);

        // File header
        out.push_str("// SPDX-License-Identifier: BUSL-1.1\n");
        out.push_str("// Copyright (c) 2026 HYPERI PTY LIMITED\n");
        out.push_str("//\n");
        out.push_str("// Generated by dfe-codegen. Do not edit.\n\n");

        // Imports
        out.push_str("use dfe_runtime::prelude::*;\n\n");

        // Struct definition
        out.push_str(&format!(
            "/// Transform for the `{}` pipeline.\n",
            self.module_name
        ));
        out.push_str(&format!("pub struct {};\n\n", struct_name));

        // Transform impl
        out.push_str(&format!("impl Transform for {} {{\n", struct_name));
        out.push_str(&format!(
            "    fn name(&self) -> &str {{\n        \"{}\"\n    }}\n\n",
            self.module_name
        ));

        // transform method
        out.push_str("    fn transform(&self, event: &mut Event) -> Result<TransformResult> {\n");

        for (i, processor) in self.pipeline.processors.iter().enumerate() {
            let body = emit_processor(processor, 2)
                .with_context(|| format!("processor {} ({})", i, processor.name()))?;
            out.push_str(&body);
            out.push('\n');
        }

        // Post-processing: dedup related arrays and clean null/empty fields
        out.push_str("        // --- Post-processing (codegen-emitted) ---\n");
        out.push_str(
            "        // Dedup related.* arrays (same value can be appended multiple times)\n",
        );
        for field in &[
            "related.ip",
            "related.user",
            "related.hash",
            "related.hosts",
        ] {
            out.push_str(&format!(
                "        if let Some(Value::Array(mut arr)) = event.get(\"{field}\").cloned() {{\n\
                 \x20           dedup_array(&mut arr);\n\
                 \x20           event.set(\"{field}\", Value::Array(arr))?;\n\
                 \x20       }}\n"
            ));
        }
        out.push_str(
            "        // Final cleanup: remove null/empty fields created during processing\n",
        );
        out.push_str("        painless_drop_empty(event.as_value_mut());\n\n");

        out.push_str("        Ok(TransformResult::Continue)\n");
        out.push_str("    }\n");
        out.push_str("}\n");

        Ok(out)
    }

    /// Generate just the transform body (statements only, no struct/impl wrapper).
    ///
    /// Useful for testing individual processor codegen.
    pub fn generate_body(&self) -> Result<String> {
        let mut out = String::with_capacity(2048);
        for (i, processor) in self.pipeline.processors.iter().enumerate() {
            let body = emit_processor(processor, 0)
                .with_context(|| format!("processor {} ({})", i, processor.name()))?;
            out.push_str(&body);
            out.push('\n');
        }
        Ok(out)
    }
}

/// Generate Rust code for a standalone pipeline (no struct wrapping).
///
/// Returns the body of a transform function.
pub fn codegen_pipeline_body(pipeline: &Pipeline) -> Result<String> {
    let cg = PipelineCodegen::new(pipeline, "anonymous");
    cg.generate_body()
}

/// Convert a snake_case or kebab-case name to PascalCase.
fn to_pascal_case(s: &str) -> String {
    s.split(['_', '-'])
        .filter(|part| !part.is_empty())
        .map(|part| {
            let mut chars = part.chars();
            match chars.next() {
                Some(first) => {
                    let mut s = first.to_uppercase().to_string();
                    s.extend(chars);
                    s
                }
                None => String::new(),
            }
        })
        .collect()
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn pascal_case_snake() {
        assert_eq!(to_pascal_case("cisco_asa"), "CiscoAsa");
    }

    #[test]
    fn pascal_case_kebab() {
        assert_eq!(to_pascal_case("my-pipeline"), "MyPipeline");
    }

    #[test]
    fn pascal_case_single() {
        assert_eq!(to_pascal_case("pipeline"), "Pipeline");
    }

    #[test]
    fn generate_simple_set() {
        let yaml = r#"
processors:
  - set:
      field: event.kind
      value: event
"#;
        let pipeline = Pipeline::parse(yaml).unwrap();
        let cg = PipelineCodegen::new(&pipeline, "test_pipeline");
        let code = cg.generate().unwrap();

        assert!(code.contains("pub struct TestPipeline;"));
        assert!(code.contains("impl Transform for TestPipeline"));
        assert!(code.contains("event.set("));
        assert!(code.contains("event.kind"));
    }

    #[test]
    fn generate_set_and_remove() {
        let yaml = r#"
processors:
  - set:
      field: event.kind
      value: event
  - remove:
      field: _temp
      ignore_missing: true
"#;
        let pipeline = Pipeline::parse(yaml).unwrap();
        let cg = PipelineCodegen::new(&pipeline, "multi_step");
        let code = cg.generate().unwrap();

        assert!(code.contains("pub struct MultiStep;"));
        assert!(code.contains("event.set("));
        assert!(code.contains("event.remove("));
    }

    #[test]
    fn generate_body_only() {
        let yaml = r#"
processors:
  - set:
      field: event.kind
      value: event
"#;
        let pipeline = Pipeline::parse(yaml).unwrap();
        let cg = PipelineCodegen::new(&pipeline, "test");
        let body = cg.generate_body().unwrap();

        // Body should not contain struct/impl
        assert!(!body.contains("pub struct"));
        assert!(body.contains("event.set("));
    }
}
