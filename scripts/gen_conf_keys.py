"""Write src/conf_keys.rs: the `_conf` keys each registered transform reads.

`source.conf` is set as `_conf` on every event, and a key the selected transform
never reads does nothing, so a typo would pass silently. The table lets startup
refuse it. It is read off the generated transform sources:

    scripts/gen_conf_keys.py            # rewrite src/conf_keys.rs
    scripts/gen_conf_keys.py --check    # exit 1 when it is stale

A transform's keys are the first path segment of every `_conf.<key>` it names,
in code, painless script text or plan JSON. A transform that names none reads
no `_conf` and has no row.
"""

import argparse
import re
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
REGISTRY = REPO / "src" / "registry.rs"
TRANSFORMS = REPO / "crates" / "dfe-transforms" / "src" / "filebeat"
OUTPUT = REPO / "src" / "conf_keys.rs"

# `("filebeat.okta.default", &filebeat::okta::default::Default,`
ENTRY = re.compile(r'\(\s*"([^"]+)",\s*&filebeat::(\w+)::(\w+)::Default,')

# `_conf.tz_map`, `ctx._conf?.drop_status` and `_conf['tz_map']`. The lookbehind
# keeps `_temp_conf.x` and `my_conf.x` out.
KEY = re.compile(
    r"(?<![A-Za-z0-9])_conf"
    r"(?:\??\.([A-Za-z_][A-Za-z0-9_]*)|\[\s*['\"]([A-Za-z_][A-Za-z0-9_]*)['\"])"
)


class RegistryError(Exception):
    """The registry or a transform it names cannot be read."""


def registered(registry: str) -> dict[str, tuple[str, str]]:
    """Map each variant name in *registry* to the module and file its transform is in."""
    entries = {name: (mod, file) for name, mod, file in ENTRY.findall(registry)}
    if not entries:
        raise RegistryError("no transform entries found in src/registry.rs")
    return entries


def keys_in(source: str) -> list[str]:
    """Return the sorted, distinct `_conf` keys *source* names."""
    return sorted({dotted or bracketed for dotted, bracketed in KEY.findall(source)})


def table(*, registry: str, transforms: Path) -> dict[str, list[str]]:
    """Map each variant that reads any `_conf` key to the keys it reads."""
    rows = {}
    for name, (mod, file) in sorted(registered(registry).items()):
        path = transforms / mod / f"{file}.rs"
        if not path.is_file():
            raise RegistryError(f"{name} names {path}, which does not exist")
        keys = keys_in(path.read_text(encoding="utf-8"))
        if keys:
            rows[name] = keys
    return rows


def render(rows: dict[str, list[str]]) -> str:
    """Return the Rust source for *rows*, sorted by variant so lookup can bisect."""
    lines = [
        "// SPDX-License-Identifier: BUSL-1.1",
        "// Copyright (c) 2026 HYPERI PTY LIMITED",
        "",
        "//! The `_conf` keys each transform reads, for refusing a `source.conf` key none reads.",
        "//!",
        "//! Generated by `scripts/gen_conf_keys.py` from the transform sources. Do not edit by hand.",
        "",
        "/// Transform variant to the `_conf` keys it reads, sorted by variant. A variant with no",
        "/// row reads none.",
        "#[rustfmt::skip]",
        "pub(crate) static CONF_KEYS: &[(&str, &[&str])] = &[",
    ]
    for name in sorted(rows):
        keys = ", ".join(f'"{key}"' for key in rows[name])
        lines.append(f'    ("{name}", &[{keys}]),')
    lines.append("];")
    return "\n".join(lines) + "\n"


def main(argv: list[str] | None = None) -> int:
    """Rewrite the table, or with --check report whether it is stale."""
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument(
        "--check", action="store_true", help="exit 1 when the file is stale"
    )
    args = parser.parse_args(argv)
    try:
        registry = REGISTRY.read_text(encoding="utf-8")
        text = render(table(registry=registry, transforms=TRANSFORMS))
    except RegistryError as exc:
        print(f"gen_conf_keys: {exc}", file=sys.stderr)
        return 2
    stale = not OUTPUT.exists() or OUTPUT.read_text(encoding="utf-8") != text
    if args.check:
        if stale:
            print(
                f"{OUTPUT.relative_to(REPO)} is stale against the transforms: "
                "run scripts/gen_conf_keys.py",
                file=sys.stderr,
            )
        return 1 if stale else 0
    if stale:
        OUTPUT.write_text(text, encoding="utf-8", newline="\n")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
