"""Write src/detect/labels.rs from the dfe-schemas catalogue.

The catalogue names each source (the `_source` dfe-loader routes on) and the
transform variant that produces it. Run against a dfe-schemas clone:

    scripts/gen_detect_labels.py /projects/dfe-schemas > src/detect/labels.rs
"""

import subprocess
import sys

import yaml

REF = "origin/main"


def git(repo: str, *args: str, stdin: str | None = None) -> str:
    return subprocess.run(
        ["git", "-C", repo, *args],
        input=stdin,
        capture_output=True,
        text=True,
        encoding="utf-8",
        errors="replace",
        check=True,
    ).stdout


def main(repo: str) -> None:
    sha = git(repo, "rev-parse", REF).strip()
    paths = [
        p
        for p in git(repo, "ls-tree", "-r", "--name-only", REF).splitlines()
        if p.startswith("catalogue/") and p.endswith(".yaml")
    ]
    labels: dict[str, str] = {}
    for path in paths:
        doc = yaml.safe_load(git(repo, "show", f"{REF}:{path}").split("\n---\n")[0])
        transform = doc.get("transform") or {}
        if transform.get("engine") != "elastic":
            continue
        variant = transform["variant"]
        if variant in labels:
            sys.exit(f"{variant} is named by two catalogue entries")
        labels[variant] = doc["source"]

    print("// SPDX-License-Identifier: BUSL-1.1")
    print("// Copyright (c) 2026 HYPERI PTY LIMITED")
    print()
    print(
        "//! The `_source` label each transform's output carries, from the dfe-schemas"
    )
    print(f"//! catalogue at {sha}.")
    print("//!")
    print("//! Generated by `scripts/gen_detect_labels.py`. Do not edit by hand.")
    print()
    print("/// Transform variant to catalogue source, sorted by variant.")
    print("static LABELS: &[(&str, &str)] = &[")
    for variant in sorted(labels):
        print(f'    ("{variant}", "{labels[variant]}"),')
    print("];")
    print()
    print("/// The catalogue source a transform's events are stamped with.")
    print("#[must_use]")
    print("pub fn label(variant: &str) -> Option<&'static str> {")
    print("    LABELS")
    print("        .binary_search_by_key(&variant, |&(v, _)| v)")
    print("        .ok()")
    print("        .map(|i| LABELS[i].1)")
    print("}")


if __name__ == "__main__":
    main(sys.argv[1])
